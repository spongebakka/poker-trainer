// Builds data.js: the 169x169 preflop equity matrix and heads-up push/fold Nash charts.
// Run: node tools/precompute.js [trialsPerMatchup]   (default 6000; takes a minute or two)
"use strict";
const fs = require("fs"), path = require("path");
const PE = require("../engine.js");
const { CLASSES, evaluate } = PE;
const N = 169, T = +(process.argv[2] || 6000);

// Seeded RNG so rebuilds are reproducible.
let seed = 123456789;
const rng = () => { seed ^= seed << 13; seed ^= seed >>> 17; seed ^= seed << 5; return ((seed >>> 0) / 4294967296); };

// ---- equity matrix: E[i][j] = equity of class i vs class j (ties split) ----
const E = new Float64Array(N * N);
const h1 = new Array(7), h2 = new Array(7);
const t0 = Date.now();
for (let i = 0; i < N; i++) {
  for (let j = i; j < N; j++) {
    const A = CLASSES[i].combos, B = CLASSES[j].combos;
    // usable combo pairs (no shared card)
    const pairs = [];
    for (const a of A) for (const b of B) if (a[0] !== b[0] && a[0] !== b[1] && a[1] !== b[0] && a[1] !== b[1]) pairs.push([a, b]);
    let win = 0;
    for (let t = 0; t < T; t++) {
      const [a, b] = pairs[Math.floor(rng() * pairs.length)];
      h1[0] = a[0]; h1[1] = a[1]; h2[0] = b[0]; h2[1] = b[1];
      let k = 2;
      let lo = 0, hi = 0;
      for (const c of [a[0], a[1], b[0], b[1]]) { if (c < 32) lo |= 1 << c; else hi |= 1 << (c - 32); }
      while (k < 7) {
        const c = Math.floor(rng() * 52);
        const bit = c < 32 ? (lo >>> c) & 1 : (hi >>> (c - 32)) & 1;
        if (bit) continue;
        if (c < 32) lo |= 1 << c; else hi |= 1 << (c - 32);
        h1[k] = c; h2[k] = c; k++;
      }
      const s1 = evaluate(h1), s2 = evaluate(h2);
      win += s1 > s2 ? 1 : s1 === s2 ? 0.5 : 0;
    }
    // a class against itself is symmetric: exactly 50%
    E[i * N + j] = i === j ? 0.5 : win / T;
    E[j * N + i] = 1 - E[i * N + j];
  }
  if (i % 13 === 12) process.stdout.write(`row ${i + 1}/169  ${((Date.now() - t0) / 1000).toFixed(0)}s\n`);
}

// ---- blocker-aware combo weights: W[i][j] = avg # of j combos available given one i combo ----
const W = new Float64Array(N * N);
for (let i = 0; i < N; i++) for (let j = 0; j < N; j++) {
  let tot = 0;
  for (const a of CLASSES[i].combos) for (const b of CLASSES[j].combos)
    if (a[0] !== b[0] && a[0] !== b[1] && a[1] !== b[0] && a[1] !== b[1]) tot++;
  W[i * N + j] = tot / CLASSES[i].combos.length;
}

// ---- heads-up push/fold Nash by fictitious play ----
// S = effective stack in big blinds BEFORE posting. SB posts 0.5, BB posts 1, no ante.
// SB: fold = -0.5; shove: BB folds -> +1, BB calls -> eq*2S - S.
// BB: fold = -1; call = eq*2S - S.
function nash(S, iters = 600) {
  const push = new Float64Array(N).fill(1), call = new Float64Array(N).fill(0.3);
  for (let it = 1; it <= iters; it++) {
    const brCall = new Float64Array(N), brPush = new Float64Array(N);
    for (let j = 0; j < N; j++) { // BB best response to push range
      let w = 0, e = 0;
      for (let i = 0; i < N; i++) { const x = push[i] * W[j * N + i]; w += x; e += x * E[j * N + i]; }
      const eq = w ? e / w : 0;
      brCall[j] = eq * 2 * S - S > -1 ? 1 : 0;
    }
    for (let i = 0; i < N; i++) { // SB best response to call range
      let wAll = 0, wC = 0, e = 0;
      for (let j = 0; j < N; j++) { const w0 = W[i * N + j]; wAll += w0; const x = call[j] * w0; wC += x; e += x * E[i * N + j]; }
      const pc = wC / wAll, eq = wC ? e / wC : 0;
      const ev = (1 - pc) * 1 + pc * (eq * 2 * S - S);
      brPush[i] = ev > -0.5 ? 1 : 0;
    }
    const a = 1 / (it + 1);
    for (let k = 0; k < N; k++) { push[k] += (brPush[k] - push[k]) * a; call[k] += (brCall[k] - call[k]) * a; }
  }
  return { push, call };
}
const STACKS = [];
for (let s = 1; s <= 20; s++) STACKS.push(s);
STACKS.push(25);
const nashOut = { stacks: STACKS, push: {}, call: {} };
for (const S of STACKS) {
  const { push, call } = nash(S);
  const enc = arr => Array.from(arr, x => Math.min(9, Math.round(x * 9))).join(""); // 0..9 frequency
  nashOut.push[S] = enc(push); nashOut.call[S] = enc(call);
}

// ---- equity vs a random hand (for ordering hands by raw strength) ----
const eqRand = [];
for (let i = 0; i < N; i++) {
  let w = 0, e = 0;
  for (let j = 0; j < N; j++) { w += W[i * N + j]; e += W[i * N + j] * E[i * N + j]; }
  eqRand.push(Math.round(e / w * 1000));
}

const out = {
  note: `Generated by tools/precompute.js with ${T} trials per matchup.`,
  eq: Array.from(E, x => Math.round(x * 1000)),
  w: Array.from(W, x => Math.round(x * 100) / 100),
  eqRand, nash: nashOut,
};
fs.writeFileSync(path.join(__dirname, "..", "data.js"),
  "/* generated by tools/precompute.js, do not edit */\n(function(r){var D=" + JSON.stringify(out) +
  ";if(typeof module!=='undefined'&&module.exports)module.exports=D;else r.PDATA=D;})(typeof window!=='undefined'?window:globalThis);\n");
console.log(`done in ${((Date.now() - t0) / 1000).toFixed(0)}s`);
